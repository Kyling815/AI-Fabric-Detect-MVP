"""Phase18 offline governance. Audit/evaluate NEVER activates any registry.

--manual-activation-request is a distinct, explicit, hash-pinned operator action.
No trained candidate, fresh dataset or thresholds are generated by this tool.
"""

import argparse
import csv
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.app.core.release_governance import AcceptancePolicy, ArtifactPin, ManualApproval
from backend.app.services.release_governance import (activate_manually, assess_release, blocked_report,
    canonical_json, digest, load, read_pin)


def audit_current():
    report = blocked_report(["NO_VERIFIED_TRAINED_PRODUCTION_CANDIDATE", "NO_VALID_FRESH_SOURCE_LOT_CAMERA_DISJOINT_LOCKED_TEST",
                             "NO_APPROVED_ACCEPTANCE_POLICY_OR_CUSTOMER_SLA"])
    policy = AcceptancePolicy.model_validate_json((ROOT / "config/release_policy_unapproved_example.json").read_bytes())
    masked_real, masked_synthetic, missing_groups = 0, 0, set()
    for path in sorted((ROOT / "storage/metadata/company_demo_manifests").glob("*_all.csv")):
        with path.open(encoding="utf-8", newline="") as stream:
            rows = list(csv.DictReader(stream))
        for row in rows:
            if row.get("mask_path"):
                masked_real += row.get("origin") == "real"
                masked_synthetic += row.get("origin") == "synthetic"
        if rows:
            missing_groups |= {key for key in ("roll_id", "lot_id", "camera_id") if key not in rows[0]}
    registry = json.loads((ROOT / "storage/metadata/fabric_registry.json").read_bytes())
    report.update(scope="CURRENT_PROJECT_READ_ONLY_PREFLIGHT_NOT_ACCEPTANCE_EVALUATION",
        trained_candidate_supplied=False, fresh_dataset_supplied=False,
        model_predictions_generated=False, historical_images_evaluated=False,
        masked_company_rows={"real": masked_real, "synthetic": masked_synthetic},
        missing_company_provenance_fields=sorted(missing_groups),
        registry_fabric_statuses={key: value["status"] for key, value in registry["fabrics"].items()},
        policy_approved=policy.approved_by is not None, customer_thresholds_defined=False,
        fp32_phase17_scope="technical/research baseline ONLY; no full-pipeline/quality evidence",
        fp16_status="REJECTED_NO_FALLBACK", phase17_research_probe_registered=False)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--audit-current", action="store_true")
    mode.add_argument("--bundle", type=Path)
    parser.add_argument("--bundle-sha256")
    parser.add_argument("--trusted-local", action="store_true")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--manual-activation-request", type=Path)
    parser.add_argument("--request-sha256")
    args = parser.parse_args()
    if args.audit_current and any((args.bundle_sha256, args.trusted_local, args.output_dir,
                                  args.manual_activation_request, args.request_sha256)):
        parser.error("Read-only audit cannot be combined with evaluation/activation arguments")
    if args.bundle and not (args.bundle_sha256 and args.trusted_local):
        parser.error("Bundle requires explicit hash and --trusted-local")
    if bool(args.manual_activation_request) != bool(args.request_sha256):
        parser.error("Manual activation requires a hash-pinned request")
    if args.output_dir and args.manual_activation_request:
        parser.error("Report generation and manual activation are distinct invocations")
    try:
        if args.audit_current:
            result = audit_current()
        else:
            bundle_pin = ArtifactPin(path=str(args.bundle.resolve()), sha256=args.bundle_sha256)
            if args.manual_activation_request:
                request = json.loads(read_pin(ArtifactPin(path=str(args.manual_activation_request.resolve()), sha256=args.request_sha256), 1024 * 1024))
                if set(request) != {"report", "registry_path", "approval"}:
                    raise ValueError("Explicit report, registry_path and approval required")
                result = activate_manually(bundle_pin, ArtifactPin.model_validate(request["report"]), request["registry_path"],
                                          ManualApproval.model_validate_json(json.dumps(request["approval"])), trusted_local=True)
            else:
                result = assess_release(bundle_pin, trusted_local=True)
                if args.output_dir:
                    target = args.output_dir.resolve()
                    base = (ROOT / "storage/models/release_governance").resolve()
                    if target.parent != base or target.exists():
                        raise ValueError("Use a NEW direct version directory in storage/models/release_governance")
                    target.mkdir(parents=True, exist_ok=False)
                    raw = canonical_json(result)
                    with (target / "acceptance_report.json").open("xb") as stream:
                        stream.write(raw)
                    result = {"report": str(target / "acceptance_report.json"), "report_sha256": digest(raw), **result}
    except Exception as exc:
        print(json.dumps({"phase": 18, "status": "ERROR_STOP_NO_ACTIVATION", "accepted": False,
                          "error_type": type(exc).__name__, "message": str(exc)}, allow_nan=False), file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2, ensure_ascii=False, allow_nan=False))
    if args.audit_current:
        return 0  # Audit executed successfully; readiness is explicitly BLOCKED.
    return 0 if result.get("accepted") or result.get("activated") else 2


if __name__ == "__main__":
    raise SystemExit(main())
